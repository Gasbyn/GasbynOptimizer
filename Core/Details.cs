    public static IReadOnlyList<Tweak> Apply(IReadOnlyList<Tweak> tweaks)
    {
        foreach (var tweak in tweaks)
        {
            if (Texts.TryGetValue(tweak.Id, out var text) && text.Length > 0) tweak.Detail = text;
            else if (tweak.Id.StartsWith("app-", StringComparison.Ordinal))
                tweak.Detail = "Co to dělá: Odinstaluje aplikaci z Windows pro všechny uživatele. " + tweak.Description +
                               "\nProč ho chceš: Uvolní místo a aplikace nebude běžet na pozadí ani se ti nebude připomínat." +
                               "\nNa co si dát pozor: Lze kdykoli znovu nainstalovat z Microsoft Store.";
            else
                tweak.Detail = "Co to dělá: " + tweak.Description + (tweak.Note.Length > 0 ? "\nNa co si dát pozor: " + tweak.Note : "");
        }
        return tweaks;
    }
